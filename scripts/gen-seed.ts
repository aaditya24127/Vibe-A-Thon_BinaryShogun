import { writeFileSync } from "node:fs";
import { SEED_BATCHES, SEED_DONORS, SEED_RIDERS, SEED_RULES, SEED_SETTINGS, SEED_SHELTERS } from "../src/lib/seed";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: readonly string[]) => `array[${a.map(q).join(",")}]::text[]`;
const lines: string[] = [];

lines.push("truncate action_log, events, incidents, unresolved, leases, allocations, batches, riders, shelters, donors, compatibility_rules, settings restart identity cascade;");
for (const [k, v] of ["batch_seq:1100", "alloc_seq:1", "lease_seq:1", "unresolved_seq:1", "incident_seq:1"].map((x) => x.split(":"))) {
  lines.push(`perform setval('${k}', ${v}, false);`);
}
for (const [k, [v, note]] of Object.entries(SEED_SETTINGS)) lines.push(`insert into settings(key, value, note) values (${q(k)}, ${v}, ${q(note)});`);
for (const d of SEED_DONORS) lines.push(`insert into donors values (${q(d.id)}, ${q(d.name)}, ${q(d.type)}, ${d.lat}, ${d.lng}, ${q(d.area_name)});`);
for (const s of SEED_SHELTERS) {
  lines.push(`insert into shelters(id, name, lat, lng, area_name, total_capacity, unmet_demand, status, accepted_categories, has_water, has_cooking_fuel, has_cold_storage) values (${q(s.id)}, ${q(s.name)}, ${s.lat}, ${s.lng}, ${q(s.area_name)}, ${s.total_capacity}, ${s.unmet_demand}, ${q(s.status)}, ${arr(s.accepted_categories)}, ${s.has_water}, ${s.has_cooking_fuel}, ${s.has_cold_storage});`);
}
for (const r of SEED_RULES) lines.push(`insert into compatibility_rules values (${q(r.id)}, ${q(r.category)}, ${arr(r.required_resources)}, ${q(r.source_note)}, ${r.verified});`);
for (const r of SEED_RIDERS) {
  lines.push(`insert into riders(id, name, capacity_units, lat, lng, last_heartbeat_at) values (${q(r.id)}, ${q(r.name)}, ${r.capacity_units}, ${r.lat}, ${r.lng}, sim_now());`);
}
for (const b of SEED_BATCHES) {
  lines.push(`insert into batches(id, donor_id, item_name, category, quantity, remaining_qty, unit, pickup_window_start, pickup_window_end, expires_at, safe_by_at, handling_notes, storage_requirement, compatibility_requirement, status) values (${q(b.id)}, ${q(b.donor_id)}, ${q(b.item_name)}, ${q(b.category)}, ${b.quantity}, ${b.quantity}, ${q(b.unit)}, sim_now() + interval '${b.start} minutes', sim_now() + interval '${b.end} minutes', sim_now() + interval '${b.expires} minutes', _safe_by_calc(${q(b.donor_id)}, ${q(b.category)}, sim_now() + interval '${b.expires} minutes'), ${q(b.handling)}, ${q(b.storage)}, ${q(b.compat)}, 'AVAILABLE');`);
  lines.push(`perform _event('batch', ${q(b.id)}, null, 'AVAILABLE', 'Batch posted by donor', 'created', ${b.quantity});`);
}
lines.push("perform setval('batch_seq', 1100, false);");

const sql = `-- Generated by scripts/gen-seed.ts from src/lib/seed.ts. Do not edit by hand.
-- _seed_data() restores the seeded operating state; reset_simulation() calls it.
create or replace function _seed_data() returns void
language plpgsql security definer set search_path = public as $$
begin
  ${lines.join("\n  ")}
end $$;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke execute on function _seed_data() from public, anon, authenticated;
  end if;
end $$;

select _seed_data();
`;
writeFileSync(new URL("../supabase/migrations/0005_seed.sql", import.meta.url), sql);
console.log(`wrote 0005_seed.sql (${lines.length} statements)`);
